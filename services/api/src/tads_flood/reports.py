"""Deterministic facts boundary. This fallback is explicitly not an AI copilot."""
from .models import Assessment
from html import escape


def build_report(assessment: Assessment):
    facts = {
        "potentially_isolated_count": assessment.summary.potentially_isolated_count,
        "unknown_network_count": assessment.summary.unknown_network_count,
    }
    claims = [{"claim_id": s.settlement_id, "text": s.reason,
               "evidence_ids": s.evidence_ids} for s in assessment.settlements]
    return {"assessment_id": assessment.assessment_id, "mode": assessment.mode,
            "generator": "deterministic_template", "ai_ready": False, "language": "en",
            "facts": facts, "claims": claims, "limitations": assessment.limitations}


def render_brief(assessment, report):
    """Bounded printable HTML; external labels are escaped before rendering."""
    title = "Situation brief" if report["language"] == "en" else "अवस्था विवरण"
    claims = report["claims"][:8]
    if len(report["claims"]) > len(claims):
        selected_note = f"<p><small>Showing {len(claims)} selected claims of {len(report['claims'])}; use the JSON brief for all claims.</small></p>"
    else:
        selected_note = ""
    items = "".join("<li>" + escape(c["text"]) + " <small>[" + escape(", ".join(c["evidence_ids"])) + "]</small></li>" for c in claims)
    source_rows = "".join("<li>" + escape(s.source_id) + " · " + escape(s.acquired_at.isoformat()) + "</li>" for s in assessment.sources)
    limits = ["Educational prototype. Candidate exposure is not confirmed damage or verified road closure.",
              "Coverage: " + assessment.quality.status + "; method: " + assessment.quality.method_version,
              "Finite-AOI road topology and unvalidated SAR thresholds limit reliability."]
    if assessment.mode == "synthetic":
        limits.insert(0, "SYNTHETIC TRAINING SCENE — not a real flood assessment.")
    if not report["translation_reviewed"]:
        limits.insert(0, "Nepali draft — fluent review is pending.")
    warning_rows = "".join("<li>" + escape(text) + "</li>" for text in limits)
    return f'''<!doctype html><html lang="{report['language']}"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1"><title>TADS Flood — {title}</title>
<style>body{{font:13px/1.45 system-ui,sans-serif;color:#183129;max-width:760px;margin:30px auto;padding:20px}}
h1{{font-size:25px;margin:0}}h2{{font-size:15px;margin:20px 0 6px}}li{{margin:6px 0;overflow-wrap:anywhere}}
small{{color:#40574e}}header{{border-bottom:2px solid #17634e;padding-bottom:12px}}.mode{{font-weight:600}}
@page{{size:A4;margin:15mm}}@media print{{body{{padding:0;margin:0;font-size:11px}}h1{{font-size:20px}}li{{margin:4px 0}}}}
</style></head><body><header><h1>TADS Flood · {title}</h1><div class="mode">{escape(assessment.mode.upper())}</div>
<small>Assessment: {escape(assessment.assessment_id)} · Event: {assessment.event_date.isoformat()}<br>
Generated: {escape(assessment.generated_at.isoformat())} · Generator: {escape(report['generator'])}</small></header>
<h2>Source-backed findings</h2><ul>{items}</ul>{selected_note}<h2>Limitations</h2><ul>{warning_rows}</ul>
<h2>Source register</h2><ul>{source_rows}</ul><small>Evidence IDs resolve in the assessment inspector.
Numbers are inserted from computed facts; they are not generated by the language model.</small></body></html>'''
